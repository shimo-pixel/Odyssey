export function getLocale() {
  const prefs = getPrefs();
  return prefs.locale === 'en' ? 'en' : 'zh';
}

export function t(key, params = {}, locale = getLocale()) {
  let text = messages[locale]?.[key] ?? messages.zh[key] ?? key;
  for (const [k, v] of Object.entries(params)) {
    text = text.replaceAll(`{${k}}`, String(v));
  }
  return text;
}

export function setDocumentTitle() {
  document.title = t('app.title');
}

export function unitLabel(unit, locale = getLocale()) {
  return t(`unit.${unit}`, {}, locale) || unit;
}

export function unitPlural(unit, locale = getLocale()) {
  const map = { day: 'unit.day', week: 'unit.week', month: 'unit.month', quarter: 'unit.quarter', year: 'unit.year' };
  return t(map[unit] || 'unit.month', {}, locale);
}
